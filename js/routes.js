export const CATALOG = seeds.map((s) => {
    const m = meta(s.stops);
    return {
        ...s,
        stops: s.stops.map((st) => ({ ...st, photo: st.photo ?? s.photo })),
        hours: m.hours,
        km: m.km,
        cost: m.cost,
    };
});
/** Все известные места — из них подбираем замену точки */
export const STOP_POOL = CATALOG.flatMap((r) => r.stops).filter((s, i, arr) => arr.findIndex((x) => x.id === s.id) === i);
